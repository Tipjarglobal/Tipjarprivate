  m = m.replace(/Über\s+(\d+(?:[.,]\d+)?)/gi, (_, n) => `${t("mkt.ovr")} ${n.replace(",", ".")}`);
  m = m.replace(/Unter\s+(\d+(?:[.,]\d+)?)/gi, (_, n) => `${t("mkt.und")} ${n.replace(",", ".")}`);
